import base64
import copy
import json
import re
from datetime import datetime, timedelta, timezone
from pathlib import Path
from urllib.parse import urlsplit

from playwright.sync_api import Page, expect, sync_playwright

NOTEBOOK_KEY = "quantum-scout:reading-desk:v1"
INJECTION = '<img src=x onerror="window.newsInjected=true">'
PREVIEW_ORIGIN = "https://images.example.org"
PREVIEW_PNG = base64.b64decode(
    "iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAwMCAO+jZXYAAAAASUVORK5CYII="
)
SOURCE_TITLE = "Quantum computing control experiment \u2014 the publisher's original wording"


def dashboard_fixture() -> dict:
    """Keep other dashboard sections intact while replacing only the news inputs."""
    payload = copy.deepcopy(
        json.loads(Path("site/data/dashboard.json").read_text(encoding="utf-8"))
    )
    # Exercise legacy snapshot compatibility independently of curated-feed tests.
    payload.pop("news_intelligence", None)
    now = datetime.now(timezone.utc)
    payload["collected_at"] = now.isoformat()
    today = now.date().isoformat()
    yesterday = (now - timedelta(days=1)).date().isoformat()

    def story(identifier, title, topic, *, priority=1, report=today, date=yesterday):
        return {
            "id": identifier,
            "title": title,
            "url": f"https://{identifier}.example.org/news/{identifier}",
            "source": "Synthetic browser fixture",
            "source_kind": "industry",
            "source_kind_label": "Industry source",
            "source_kind_note": "Synthetic browser test; not a real news item.",
            "authority": "Industry source",
            "category": topic,
            "date": date,
            "date_label": "Published",
            "report_date": report,
            "summary": f"Fixture excerpt for {title}. No real-world claim is being made.",
            "context": "Fixture topic context, not an independently verified impact assessment.",
            "key_points": ["A synthetic source excerpt used only for browser regression testing."],
            "lenses": [topic],
            "related": [],
            "score": priority * 10,
            "decision_brief": {
                "version": 1,
                "priority": priority,
                "impact": "Synthetic context only; verify the original source.",
                "topics": [topic],
            },
        }

    stories = [
        # Deliberately shuffled: input order and priority must not determine recent ordering.
        story(
            "older-high",
            "Federal procurement announcement in an earlier report",
            "government",
            priority=3,
            report=yesterday,
        ),
        story("latest-quantum", SOURCE_TITLE, "quantum"),
        story("latest-security", "PQC security migration update", "security", priority=3),
        story("latest-ai", "AI model evaluation release", "ai", priority=2),
        story("latest-cloud", "Cloud infrastructure networking update", "cloud"),
        story("collected-only", "Federal standards reference collected today", "government"),
        story("undated", "Quantum sensing item with no publication date", "quantum", date=""),
        story("escaped-title", f"AI model title {INJECTION}", "ai"),
    ]
    stories[5].update(date=today, date_label="Collected")
    stories[6]["date_label"] = "Publication date unavailable"
    stories[6]["summary"] = "Generic autogenerated category fallback; not a source excerpt."
    stories[6]["key_points"] = []
    stories.extend(
        story(f"security-{index:02}", f"Security inventory fixture {index:02}", "security")
        for index in range(12)
    )

    def preview(item: dict, **overrides) -> dict:
        return {
            "image_url": f"{PREVIEW_ORIGIN}/preview/{item['id']}.png",
            "page_url": item["url"],
            "publisher": item["source"],
            "provenance": "og:image",
            "fetched_at": now.isoformat(),
            "status": "ok",
            **overrides,
        }

    for item in stories[1:5]:
        item["image"] = preview(item)
    # A failed publisher image must become a text-only card, not a broken icon.
    stories[4]["image"]["image_url"] = f"{PREVIEW_ORIGIN}/preview/broken.png"
    invalid_previews = [
        {"image_url": "http://images.example.org/insecure.png"},
        {"image_url": "https://user:password@images.example.org/credentials.png"},
        {"image_url": "https://127.0.0.1/private.png"},
        {"image_url": "https://localhost/private.png"},
        {"image_url": "https://10.0.0.1/private.png"},
        {"image_url": f"{PREVIEW_ORIGIN}/private.png?api_key=not-a-real-key"},
        {"image_url": "javascript:window.newsInjected=true"},
        {"page_url": "https://example.org/news/a-different-story"},
        {"status": "unavailable"},
        {"image_url": "data:image/png;base64,not-an-image"},
        {"image_url": "https://[::1]/private.png"},
        {"image_url": "https://169.254.169.254/private.png"},
    ]
    for item, invalid in zip(stories[8:], invalid_previews, strict=True):
        item["image"] = preview(item, **invalid)
    # Each clickable topic needs three stories under the new coverage threshold.
    for topic, count in [("quantum", 1), ("ai", 1), ("cloud", 2), ("government", 1)]:
        stories.extend(
            story(f"extra-{topic}-{i}", f"Additional {topic} subject {i}", topic)
            for i in range(count)
        )
    duplicate = copy.deepcopy(stories[1])
    duplicate.update(
        id="duplicate-quantum",
        url=stories[1]["url"] + "/?utm_source=fixture#section",
    )
    unsafe = story("unsafe-url", "Unsafe source URL fixture", "security")
    unsafe["url"] = "javascript:window.newsInjected=true"
    blank = story("empty-title", "", "security")
    stories.extend([duplicate, unsafe, blank])
    payload["reading_brief"].update(
        stories=stories,
        edition_date=today,
        collected_at=now.isoformat(),
        coverage={
            "window_start": yesterday,
            "window_end": today,
            "item_count": len(stories),
            "dated_item_count": len(stories) - 1,
            "undated_item_count": 1,
            "report_count": 2,
        },
    )
    return payload


def displayed_ids(page: Page) -> list[str]:
    return page.locator("#news article[data-news-id]").evaluate_all(
        "nodes => nodes.map(node => node.dataset.newsId)"
    )


def open_tools(page: Page) -> None:
    """Open secondary controls, preserving the default story-first presentation."""
    tools = page.locator("#news-tools")
    if tools.count() and not tools.evaluate("node => node.open"):
        tools.locator(":scope > summary").click()


def reset_filters(page: Page) -> None:
    open_tools(page)
    page.locator('#news-filter-buttons [data-news-topic="all"]').click()
    page.locator("#news-search").fill("")
    page.locator("#news-sort").select_option("recent")


def assert_no_overflow(page: Page) -> None:
    assert page.evaluate("document.documentElement.scrollWidth <= innerWidth + 1"), (
        page.viewport_size,
        page.evaluate(
            "[...document.querySelectorAll('#news *')].filter(e => "
            "e.getBoundingClientRect().right > innerWidth + 1).slice(0,8)"
            ".map(e => ({tag:e.tagName, id:e.id, class:e.className, text:e.textContent, "
            "bounds:e.getBoundingClientRect().toJSON(), parent:e.parentElement.className, "
            "parentTag:e.parentElement.tagName, parentBounds:e.parentElement.getBoundingClientRect().toJSON(), "
            "whiteSpace:getComputedStyle(e).whiteSpace, wordBreak:getComputedStyle(e).wordBreak, "
            "overflowWrap:getComputedStyle(e).overflowWrap}))"
        ),
    )


def assert_text_only_card(page: Page, identifier: str) -> None:
    card = page.locator(f'#news [data-news-id="{identifier}"]')
    expect(card).to_be_visible()
    expect(card).to_have_class(re.compile(r"\bnews-text-only\b"))
    expect(card.locator("figure, img")).to_have_count(0)
    assert card.evaluate(
        "card => { const styles = getComputedStyle(card); "
        "const available = card.clientWidth - parseFloat(styles.paddingLeft) "
        "- parseFloat(styles.paddingRight); "
        "const singleColumn = styles.display !== 'grid' "
        "|| styles.gridTemplateColumns.trim().split(/\\s+/).length === 1; "
        # The lead caps reading width at 900px while still using a single full-width grid track.
        "const readingWidth = card.classList.contains('news-lead') "
        "? Math.min(available, 900) : available; "
        "return card.querySelector('.news-copy').getBoundingClientRect().width "
        ">= readingWidth - 2 && singleColumn; }"
    ), f"Text-only card {identifier} retained an empty image column"


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--url", default="http://127.0.0.1:8765")
    parser.add_argument("--channel", default="chromium")
    parser.add_argument("--output", type=Path, default=Path("site/verification"))
    args = parser.parse_args()
    args.output.mkdir(parents=True, exist_ok=True)
    base = args.url.rstrip("/")
    origin = urlsplit(base)
    payload = dashboard_fixture()
    state = {"payload": payload, "fail": False}
    posts: list[str] = []
    errors: list[str] = []
    preview_requests: list[str] = []

    with sync_playwright() as playwright:
        browser = playwright.chromium.launch(channel=args.channel, headless=True)
        context = browser.new_context(
            viewport={"width": 1440, "height": 1050},
            reduced_motion="reduce",
            timezone_id="America/Chicago",
        )
        page = context.new_page()
        page.on("pageerror", lambda error: errors.append(str(error)))

        def intercept(route) -> None:
            request = route.request
            url = urlsplit(request.url)
            if request.method == "POST":
                posts.append(request.url)
                route.fulfill(status=503, json={"error": "Unexpected POST blocked by test"})
            elif url.path.endswith("/api/lab/config"):
                route.fulfill(json={"providers": {"gemini": False, "groq": False}})
            elif url.path.endswith("/lab-config.json"):
                route.fulfill(json={})
            elif url.path.endswith(("/data/dashboard.json", "/data/index.json")):
                if state["fail"]:
                    route.fulfill(status=503, json={"error": "Synthetic fixture unavailable"})
                else:
                    route.fulfill(json=state["payload"])
            elif request.resource_type == "image" and url.netloc == "images.example.org":
                preview_requests.append(request.url)
                if url.path == "/preview/broken.png":
                    route.fulfill(status=503, content_type="text/plain", body="Image unavailable")
                else:
                    route.fulfill(content_type="image/png", body=PREVIEW_PNG)
            elif (url.scheme, url.netloc) == (origin.scheme, origin.netloc):
                route.continue_()
            else:
                route.abort()

        context.route("**/*", intercept)
        page.goto(base + "/")
        page.wait_for_function(
            "typeof state !== 'undefined' && state.data && document.getElementById('main').getAttribute('aria-busy') !== 'true'"
        )
        assert not errors, errors
        assert not page.locator("#desk-error").is_visible(), page.locator(
            "#desk-error"
        ).inner_text()
        for invalid in (None, {}, {"url": "javascript:alert(1)"}, {"url": "not a URL"}):
            assert page.evaluate("item => ScoutNews.topics(item)", invalid) == []
        expect(page.locator("#news")).to_be_visible()
        expect(page.locator('[data-workspace="news"]')).to_have_attribute("aria-current", "page")
        expect(page.locator("#news article[data-news-id]")).to_have_count(10)
        expect(page.locator(".desk-workspace:visible")).to_have_count(1)
        expect(page.locator("#news-loading")).to_be_hidden()
        expect(page.locator("#news-status")).to_have_attribute("data-freshness", "current")

        initial = displayed_ids(page)
        assert "older-high" not in initial[:3], initial
        assert len(initial) == len(set(initial)), initial
        assert "unsafe-url" not in initial and "empty-title" not in initial
        for identifier in ["latest-security", "latest-ai", "latest-quantum"]:
            card = page.locator(f'#news [data-news-id="{identifier}"]')
            image = card.locator("img.news-publisher-image")
            expect(image).to_have_count(1)
            expect(image).to_have_attribute("src", f"{PREVIEW_ORIGIN}/preview/{identifier}.png")
            expect(image).to_have_attribute("referrerpolicy", "no-referrer")
            expect(card.locator("figcaption")).to_contain_text("Image via")
            expect(card.locator("figcaption")).to_contain_text("Synthetic browser fixture")
            image.scroll_into_view_if_needed()
            expect(image).to_have_js_property("naturalWidth", 1)
        expect(page.locator('[data-news-id="latest-quantum"] h3')).to_have_text(SOURCE_TITLE)
        assert page.locator('#news img[src^="images/news-"]').count() == 0
        expect(page.locator("#news")).not_to_contain_text("AI-generated topic illustration")
        while page.locator("#news-more").is_visible():
            previous = len(displayed_ids(page))
            page.locator("#news-more").click()
            expect(page.locator("#news article[data-news-id]")).not_to_have_count(previous)
        ids = displayed_ids(page)
        assert len(ids) == 25, ids  # Original 20 plus five minimum-topic controls.
        assert len(set(ids)) == len(ids)
        assert len({"latest-quantum", "duplicate-quantum"}.intersection(ids)) == 1
        assert ids[-1] == "older-high", ids
        assert "unsafe-url" not in ids and "empty-title" not in ids
        assert page.evaluate("window.newsInjected") is None
        expect(page.locator('#news article img[src="x"]')).to_have_count(0)
        expect(page.locator('[data-news-id="escaped-title"]')).to_contain_text(INJECTION)
        assert page.locator('#news a[href^="javascript:"]').count() == 0

        # Collected-only records must not acquire a fabricated publication date.
        collected = page.locator('[data-news-id="collected-only"]')
        expect(collected).to_contain_text("Collected", ignore_case=True)
        expect(collected).not_to_contain_text("Published", ignore_case=True)
        expect(page.locator('[data-news-id="latest-security"]')).to_contain_text(
            "Published", ignore_case=True
        )
        undated = page.locator('[data-news-id="undated"]')
        expect(undated).to_contain_text("Publication date unavailable")
        expect(undated).to_contain_text("Source excerpt unavailable")
        expect(undated).not_to_contain_text("Generic autogenerated category fallback")
        assert_text_only_card(page, "undated")
        for index in range(12):
            assert_text_only_card(page, f"security-{index:02}")
        # Rendering publisher previews must not mutate saved source evidence.
        assert payload["reading_brief"]["stories"][1]["title"] == SOURCE_TITLE

        open_tools(page)
        for topic, identifier in [
            ("security", "latest-security"),
            ("quantum", "latest-quantum"),
            ("ai", "latest-ai"),
            ("cloud", "latest-cloud"),
            ("government", "collected-only"),
        ]:
            tab = page.locator(f'#news-filter-buttons [data-news-topic="{topic}"]')
            tab.click()
            expect(tab).to_have_attribute("aria-pressed", "true")
            assert identifier in displayed_ids(page), (topic, displayed_ids(page))
            assert all(
                topic in story["lenses"]
                for story in payload["reading_brief"]["stories"]
                if story["id"] in displayed_ids(page)
            )

        reset_filters(page)
        page.locator("#news-search").fill("networking update")
        expect(page.locator("#news article[data-news-id]")).to_have_count(1)
        assert displayed_ids(page) == ["latest-cloud"]
        assert_text_only_card(page, "latest-cloud")
        assert not page.locator("#news img").count()
        page.locator("#news-search").fill("nonexistent search phrase")
        expect(page.locator("#news article[data-news-id]")).to_have_count(0)
        expect(page.locator("#news-empty")).to_be_visible()
        reset_filters(page)
        page.locator("#news-sort").select_option("relevance")
        assert "older-high" in displayed_ids(page)[:3], displayed_ids(page)
        page.locator("#news-sort").select_option("recent")
        assert "older-high" not in displayed_ids(page)[:3]

        # Reuse the real notebook, including safe persistence and cross-route updates.
        page.locator("#news-search").fill("networking update")
        save = page.locator('#news [data-save="latest-cloud"]')
        expect(save).to_have_attribute("aria-pressed", "false")
        save.click()
        expect(save).to_have_attribute("aria-pressed", "true")
        stored = page.evaluate("key => JSON.parse(localStorage.getItem(key))", NOTEBOOK_KEY)
        assert "latest-cloud" in stored["saved"]
        assert stored["stories"][0]["title"] == "Cloud infrastructure networking update"
        page.reload()
        expect(page.locator("#news article[data-news-id]")).to_have_count(10)
        open_tools(page)
        page.locator("#news-search").fill("networking update")
        expect(page.locator('#news [data-save="latest-cloud"]')).to_have_attribute(
            "aria-pressed", "true"
        )
        page.evaluate("location.hash = '#saved'")
        expect(page.locator("#saved")).to_be_visible()
        expect(page.locator("#notebook-list")).to_contain_text(
            "Cloud infrastructure networking update"
        )
        page.evaluate("location.hash = '#news'")
        expect(page.locator("#news")).to_be_visible()
        reset_filters(page)

        for width in [1440, 1040, 760, 390]:
            page.set_viewport_size({"width": width, "height": 1000 if width > 760 else 844})
            assert_no_overflow(page)
            page.locator("#news-search").fill("networking update")
            # Focus outlines and collection metadata must not overlap at any width.
            for theme in ["light", "dark"]:
                page.evaluate("theme => document.documentElement.dataset.theme = theme", theme)
                controls = page.locator(".news-controls").bounding_box()
                coverage = page.locator(".news-coverage > summary").bounding_box()
                assert controls and coverage
                assert coverage["y"] >= controls["y"] + controls["height"] + 12, (
                    width,
                    theme,
                    controls,
                    coverage,
                )
            assert_text_only_card(page, "latest-cloud")
            assert_no_overflow(page)
            page.locator("#news-search").fill("")
            if width in [1440, 390]:
                page.screenshot(path=str(args.output / f"news-{width}.png"), full_page=True)
        menu = page.locator("#workspace-menu")
        expect(menu).to_be_visible()
        menu.click()
        expect(menu).to_have_attribute("aria-expanded", "true")
        expect(page.locator('#workspace-nav [data-workspace="news"]')).to_be_visible()
        page.locator('#workspace-nav [data-workspace="news"]').click()
        expect(menu).to_have_attribute("aria-expanded", "false")
        menu.click()
        page.locator('#workspace-nav [data-workspace="news"]').focus()
        page.keyboard.press("Escape")
        expect(menu).to_have_attribute("aria-expanded", "false")
        expect(menu).to_be_focused()

        # Snapshot freshness must be honest; never claim an old collection is today's news.
        state["payload"] = copy.deepcopy(payload)
        state["payload"]["reading_brief"]["collected_at"] = (
            datetime.now(timezone.utc) - timedelta(days=10)
        ).isoformat()
        state["payload"]["collected_at"] = state["payload"]["reading_brief"]["collected_at"]
        page.reload()
        expect(page.locator("#news article[data-news-id]")).to_have_count(10)
        expect(page.locator("#news-status")).to_have_attribute("data-freshness", "stale")
        expect(page.locator("#news-status")).to_contain_text("not a live news feed")
        state["payload"]["reading_brief"]["collected_at"] = ""
        state["payload"]["collected_at"] = ""
        page.reload()
        expect(page.locator("#news-status")).to_have_attribute("data-freshness", "unknown")
        state["payload"]["reading_brief"]["collected_at"] = (
            datetime.now(timezone.utc) + timedelta(days=10)
        ).isoformat()
        state["payload"]["collected_at"] = state["payload"]["reading_brief"]["collected_at"]
        page.reload()
        expect(page.locator("#news-status")).to_have_attribute("data-freshness", "future")

        state["payload"]["reading_brief"]["stories"] = []
        page.reload()
        expect(page.locator("#news article[data-news-id]")).to_have_count(0)
        expect(page.locator("#news-empty")).to_be_visible()
        expect(page.locator("#news-more")).to_be_hidden()
        assert page.evaluate("window.ScoutNotebook.readings().length") == 1

        state["fail"] = True
        page.reload()
        expect(page.locator("#news-loading")).to_be_hidden()
        expect(page.locator("#news-status")).to_contain_text("load", ignore_case=True)
        expect(page.locator("#news article[data-news-id]")).to_have_count(0)
        assert not posts, posts
        assert not errors, errors
        assert set(preview_requests) == {
            f"{PREVIEW_ORIGIN}/preview/{identifier}.png"
            for identifier in ["latest-security", "latest-ai", "latest-quantum", "broken"]
        }, preview_requests
        print(
            json.dumps(
                {
                    "result": "passed",
                    "unique_stories": len(ids),
                    "topics": 6,
                    "distinct_publisher_previews": 3,
                    "invalid_preview_cases": 12,
                    "broken_preview_fallback": "passed",
                    "viewport_widths": [1440, 1040, 760, 390],
                    "unrequested_posts": len(posts),
                    "page_errors": len(errors),
                }
            )
        )
        context.close()
        browser.close()


if __name__ == "__main__":
    main()
